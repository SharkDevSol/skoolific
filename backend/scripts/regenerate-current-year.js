#!/usr/bin/env node
// Regenerate invoices for current academic year (months 11-13) for students without invoices
const { Pool } = require('pg');
const { PrismaClient } = require('@prisma/client');
const { toEthiopian, toGregorian } = require('../utils/ethiopianCalendar');

const pool = new Pool({
  user: process.env.DB_USER || 'iqra', host: process.env.DB_HOST || 'localhost', database: process.env.DB_NAME || 'iqrab1', password: process.env.DB_PASSWORD || '', port: 5432
});
const prisma = new PrismaClient({ datasources: { db: { url: 'postgresql://iqra:[PASSWORD]@localhost:5432/iqrab1?schema=school_comms' } } });

const ETH_MONTHS = ['Meskerem','Tikimt','Hidar','Tahsas','Tir','Yekatit','Megabit','Miazia','Ginbot','Sene','Hamle','Nehase','Pagume'];

async function main() {
  const ethNow = toEthiopian(new Date());
  const ethiopianYear = ethNow.year;
  const gregYear = ethiopianYear + 7;
  const pagumeDays = ((gregYear + 1) % 4 === 0 && ((gregYear + 1) % 100 !== 0 || (gregYear + 1) % 400 === 0)) ? 6 : 5;

  // Months to generate: current month (11) through end of academic year (13)
  const monthsToGenerate = [11, 12, 13];
  
  // Get all fee structures
  const feeStructures = await prisma.feeStructure.findMany({ include: { items: true } });
  console.log(`Fee structures: ${feeStructures.length}`);

  // Get all students from all classes
  const classes = ['G1', 'G2', 'G3', 'G4', 'G5', 'G6'];
  let totalGenerated = 0;

  for (const fs of feeStructures) {
    if (!fs.gradeLevel || !classes.includes(fs.gradeLevel)) continue;
    
    const monthlyAmount = fs.items[0] ? parseFloat(fs.items[0].amount) : 0;
    if (monthlyAmount <= 0) continue;
    const accountId = fs.items[0]?.accountId || '00000000-0000-0000-0000-000000000001';
    const campusId = fs.campusId || '00000000-0000-0000-0000-000000000001';

    // Get students in this class
    const students = await pool.query(
      `SELECT school_id, class_id, student_name FROM classes_schema."${fs.gradeLevel}" WHERE is_active != false OR is_active IS NULL`
    );
    
    console.log(`\nClass ${fs.gradeLevel}: ${students.rows.length} students`);

    for (const s of students.rows) {
      const sid = `00000000-0000-0000-${String(s.school_id).padStart(4,'0')}-${String(s.class_id).padStart(12,'0')}`;
      
      for (const targetMonth of monthsToGenerate) {
        // Check if invoice already exists
        const existing = await prisma.invoice.count({ 
          where: { 
            studentId: sid, 
            feeStructureId: fs.id,
            metadata: { path: ['monthNumber'], equals: targetMonth }
          } 
        });
        
        if (existing > 0) {
          console.log(`  ${s.student_name}: ${ETH_MONTHS[targetMonth-1]} already exists, skipping`);
          continue;
        }

        // Generate invoice
        const lastDay = targetMonth === 13 ? pagumeDays : 30;
        const dueDate = toGregorian(ethiopianYear, targetMonth, lastDay);
        dueDate.setHours(12, 0, 0, 0);

        const invoiceNumber = `INV-${Date.now()}-${sid.replace(/[^a-zA-Z0-9]/g,'').slice(-8)}-M${targetMonth}`;
        
        await prisma.invoice.create({
          data: {
            invoiceNumber,
            studentId: sid,
            academicYearId: fs.academicYearId || '00000000-0000-0000-0000-000000000001',
            feeStructureId: fs.id,
            issueDate: new Date(),
            dueDate,
            totalAmount: monthlyAmount,
            discountAmount: 0,
            lateFeeAmount: 0,
            netAmount: monthlyAmount,
            paidAmount: 0,
            status: 'ISSUED',
            campusId,
            createdBy: '00000000-0000-0000-0000-000000000001',
            metadata: {
              month: ETH_MONTHS[targetMonth-1] || `Month ${targetMonth}`,
              monthNumber: targetMonth,
              monthIndex: targetMonth - 10,
              totalMonths: 3,
              oldRegistrationFee: 0,
              newRegistrationFee: 0,
              isAutoGenerated: true,
              registrationFee: 0
            },
            items: {
              create: [{ 
                description: `${ETH_MONTHS[targetMonth-1]} Monthly Fee`, 
                feeCategory: 'TUITION', 
                amount: monthlyAmount, 
                accountId 
              }]
            }
          }
        });
        totalGenerated++;
        console.log(`  ${s.student_name}: ${ETH_MONTHS[targetMonth-1]} generated, due ${dueDate.toISOString().split('T')[0]}`);
      }
    }
  }

  console.log(`\nTotal invoices generated: ${totalGenerated}`);
  
  // Summary
  const summary = await prisma.invoice.groupBy({
    by: ['status'],
    _count: true
  });
  console.log('Invoice status summary:', summary);

  await prisma.$disconnect();
  await pool.end();
  console.log('DONE');
}

main().catch(e => { console.error(e); process.exit(1); });
