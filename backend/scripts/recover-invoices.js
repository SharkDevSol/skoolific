// Recovery script: regenerate iqrab1 invoices for all students per fee structure,
// then re-link surviving payments to their invoices.
const { Pool } = require('pg');
const { PrismaClient } = require('@prisma/client');

const pool = new Pool({
  user: 'iqra', host: 'localhost', database: 'iqrab1', password: 'iqra1768', port: 5432
});
const prisma = new PrismaClient({ datasources: { db: { url: 'postgresql://iqra:iqra1768@localhost:5432/iqrab1?schema=school_comms' } } });

const ETH_MONTHS = ['Meskerem','Tikimt','Hidar','Tahsas','Tir','Yekatit','Megabit','Miazia','Ginbot','Sene','Hamle','Nehase','Pagume'];
const { toEthiopian, toGregorian } = require('./utils/ethiopianCalendar');

async function main() {
  const ethNow = toEthiopian(new Date());
  const ethiopianYear = ethNow.year;
  const gregYear = ethiopianYear + 7;
  const pagumeDays = ((gregYear + 1) % 4 === 0 && ((gregYear + 1) % 100 !== 0 || (gregYear + 1) % 400 === 0)) ? 6 : 5;

  // 1. Get all fee structures with items
  const feeStructures = await prisma.feeStructure.findMany({ include: { items: true } });
  console.log(`Fee structures: ${feeStructures.length}`);

  let totalInvoices = 0;
  for (const fs of feeStructures) {
    if (!fs.gradeLevel) continue;
    let selectedMonths = [];
    let oldReg = 0, newReg = 0;
    try {
      const desc = (fs.description || '{}').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');
      const data = JSON.parse(desc);
      selectedMonths = data.months || [];
      oldReg = parseFloat(data.oldRegistrationFee) || 0;
      newReg = parseFloat(data.newRegistrationFee) || 0;
    } catch (e) { console.warn('bad desc for', fs.name); }
    if (selectedMonths.length === 0) continue;
    selectedMonths.sort((a, b) => a - b);

    const monthlyAmount = fs.items[0] ? parseFloat(fs.items[0].amount) : 0;
    if (monthlyAmount <= 0) continue;
    const accountId = fs.items[0]?.accountId || '00000000-0000-0000-0000-000000000001';
    const campusId = fs.campusId || '00000000-0000-0000-0000-000000000001';

    // Get students in this class
    const students = await pool.query(
      `SELECT school_id, class_id, student_name FROM classes_schema."${fs.gradeLevel}" WHERE is_active != false OR is_active IS NULL`
    );
    console.log(`Class ${fs.gradeLevel}: ${students.rows.length} students`);

    for (const s of students.rows) {
      const sid = `00000000-0000-0000-${String(s.school_id).padStart(4,'0')}-${String(s.class_id).padStart(12,'0')}`;
      const existing = await prisma.invoice.count({ where: { studentId: sid, feeStructureId: fs.id } });
      if (existing > 0) continue;

      for (let mi = 0; mi < selectedMonths.length; mi++) {
        const targetMonth = selectedMonths[mi];
        const isFirst = mi === 0;
        const lastDay = targetMonth === 13 ? pagumeDays : 30;
        const dueDate = toGregorian(ethiopianYear, targetMonth, lastDay);
        dueDate.setHours(12, 0, 0, 0);
        const registrationFee = isFirst ? newReg : 0;
        const invoiceAmount = monthlyAmount + registrationFee;

        const inv = await prisma.invoice.create({
          data: {
            invoiceNumber: `INV-${Date.now()}-${sid.replace(/[^a-zA-Z0-9]/g,'').slice(-8)}-M${targetMonth}`,
            studentId: sid,
            academicYearId: fs.academicYearId || '00000000-0000-0000-0000-000000000001',
            feeStructureId: fs.id,
            issueDate: new Date(),
            dueDate,
            totalAmount: invoiceAmount,
            discountAmount: 0,
            lateFeeAmount: 0,
            netAmount: invoiceAmount,
            paidAmount: 0,
            status: 'ISSUED',
            campusId,
            createdBy: '00000000-0000-0000-0000-000000000001',
            metadata: {
              month: ETH_MONTHS[targetMonth-1] || `Month ${targetMonth}`,
              monthNumber: targetMonth,
              monthIndex: mi + 1,
              totalMonths: selectedMonths.length,
              oldRegistrationFee: isFirst ? oldReg : 0,
              newRegistrationFee: isFirst ? newReg : 0,
              isAutoGenerated: true,
              registrationFee
            },
            items: {
              create: [{ description: `${ETH_MONTHS[targetMonth-1]} Monthly Fee`, feeCategory: 'TUITION', amount: monthlyAmount, accountId }]
            }
          }
        });
        totalInvoices++;
      }
      console.log(`  generated ${selectedMonths.length} invoices for ${s.student_name}`);
    }
  }
  console.log(`\nTotal invoices generated: ${totalInvoices}`);

  // 2. Re-link surviving payments to their invoices (match by studentId + nearest dueDate to paymentDate)
  const payments = await prisma.payment.findMany({ orderBy: { paymentDate: 'asc' } });
  console.log(`\nRe-linking ${payments.length} payments...`);
  let linked = 0;
  for (const p of payments) {
    const invoices = await prisma.invoice.findMany({ where: { studentId: p.studentId, status: 'ISSUED' } });
    if (invoices.length === 0) { console.warn(`  no invoice for payment ${p.receiptNumber}`); continue; }
    // Pick the invoice whose dueDate is closest to the payment date
    const pd = new Date(p.paymentDate);
    let best = invoices[0], bestDiff = Infinity;
    for (const inv of invoices) {
      const diff = Math.abs(new Date(inv.dueDate) - pd);
      if (diff < bestDiff) { bestDiff = diff; best = inv; }
    }
    await prisma.paymentAllocation.create({ data: { paymentId: p.id, invoiceId: best.id, amount: parseFloat(p.amount) } });
    const newPaid = parseFloat(best.paidAmount) + parseFloat(p.amount);
    const newStatus = newPaid >= parseFloat(best.netAmount) ? 'PAID' : 'PARTIALLY_PAID';
    await prisma.invoice.update({ where: { id: best.id }, data: { paidAmount: newPaid, status: newStatus } });
    linked++;
  }
  console.log(`Linked ${linked} payments to invoices`);

  await prisma.$disconnect();
  await pool.end();
  console.log('DONE');
}

main().catch(e => { console.error(e); process.exit(1); });
